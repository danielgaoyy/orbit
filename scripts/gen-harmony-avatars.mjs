#!/usr/bin/env node
/**
 * Generate static HarmonyOS SVG assets, Light/Dark background colors, and ArkTS roster metadata
 * directly from apps/desktop/src/lib/subagent-avatar.ts using Node 24 native TypeScript stripping.
 *
 * Usage:
 *   node scripts/gen-harmony-avatars.mjs          # write generated assets & ArkTS roster
 *   node scripts/gen-harmony-avatars.mjs --check  # verify repository files match generated output
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DESKTOP_AVATAR_TS = join(ROOT, 'apps/desktop/src/lib/subagent-avatar.ts');
const MEDIA_DIR = join(ROOT, 'apps/harmony/entry/src/main/resources/base/media');
const BASE_COLOR_PATH = join(ROOT, 'apps/harmony/entry/src/main/resources/base/element/color.json');
const DARK_COLOR_PATH = join(ROOT, 'apps/harmony/entry/src/main/resources/dark/element/color.json');
const ROSTER_ETS_PATH = join(
  ROOT,
  'apps/harmony/entry/src/main/ets/components/common/OrbitAvatarRoster.ets'
);

const AVATAR_COLOR_RE = /^orbit_avatar_.+_bg$/;
const AVATAR_SVG_RE = /^orbit_avatar_.+\.svg$/;

function fail(message) {
  console.error(`gen-harmony-avatars: ERROR: ${message}`);
  process.exit(1);
}

function toResourceSlug(id) {
  const slug = id.replace(/-/g, '_');
  if (!/^[a-z][a-z0-9_]*$/.test(slug)) {
    fail(`Avatar id ${JSON.stringify(id)} produces invalid Harmony resource slug ${JSON.stringify(slug)}`);
  }
  return slug;
}

/**
 * Convert #RRGGBBAA hex fills into SVG 1.1 fill + fill-opacity for universal HarmonyOS SVG rendering.
 */
function renderPathElement(layerPath) {
  const fill = layerPath.fill;
  const d = layerPath.d;
  if (/^#[0-9a-fA-F]{8}$/.test(fill)) {
    const rgb = fill.slice(0, 7);
    const alpha = parseInt(fill.slice(7, 9), 16) / 255;
    const opacity = Number(alpha.toFixed(3));
    return `  <path d="${d}" fill="${rgb}" fill-opacity="${opacity}"/>`;
  }
  return `  <path d="${d}" fill="${fill}"/>`;
}

function buildAvatarSvg(character) {
  const lines = [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64">',
  ];
  for (const layer of [character.back, character.head, character.face, character.eyes]) {
    for (const entry of layer) {
      lines.push(renderPathElement(entry));
    }
  }
  lines.push('</svg>');
  return `${lines.join('\n')}\n`;
}

function mergeColorJson(existingPath, avatarColorEntries) {
  const existing = JSON.parse(readFileSync(existingPath, 'utf8'));
  const baseColors = Array.isArray(existing.color) ? existing.color : [];
  const preserved = baseColors.filter((item) => !AVATAR_COLOR_RE.test(item.name));
  const sortedAvatarColors = [...avatarColorEntries].sort((a, b) =>
    a.name < b.name ? -1 : a.name > b.name ? 1 : 0
  );
  return `${JSON.stringify({ color: [...preserved, ...sortedAvatarColors] }, null, 2)}\n`;
}

function buildRosterEts(roster) {
  const lines = [
    '// Generated by scripts/gen-harmony-avatars.mjs from apps/desktop/src/lib/subagent-avatar.ts.',
    '// Do not edit manually; run `node scripts/gen-harmony-avatars.mjs` after updating the desktop roster.',
    '',
    'export interface OrbitSubagentAvatarAsset {',
    '  readonly id: string;',
    '  readonly name: string;',
    '  readonly nameResource: Resource;',
    '  readonly media: Resource;',
    '  readonly bgColor: Resource;',
    '}',
    '',
    'export const ORBIT_SUBAGENT_AVATAR_IDS: readonly string[] = [',
  ];
  for (const ch of roster) {
    lines.push(`  '${ch.id}',`);
  }
  lines.push('];');
  lines.push('');
  lines.push('export const ORBIT_SUBAGENT_AVATAR_ROSTER: readonly OrbitSubagentAvatarAsset[] = [');
  for (const ch of roster) {
    const slug = toResourceSlug(ch.id);
    const escapedName = ch.name.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    lines.push('  {');
    lines.push(`    id: '${ch.id}',`);
    lines.push(`    name: '${escapedName}',`);
    lines.push(`    nameResource: $r('app.string.avatar_name_${slug}'),`);
    lines.push(`    media: $r('app.media.orbit_avatar_${slug}'),`);
    lines.push(`    bgColor: $r('app.color.orbit_avatar_${slug}_bg')`);
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  lines.push('const AVATAR_ASSET_BY_ID: Map<string, OrbitSubagentAvatarAsset> = new Map<string, OrbitSubagentAvatarAsset>(');
  lines.push('  ORBIT_SUBAGENT_AVATAR_ROSTER.map(');
  lines.push('    (entry: OrbitSubagentAvatarAsset): [string, OrbitSubagentAvatarAsset] => [entry.id, entry]');
  lines.push('  )');
  lines.push(');');
  lines.push('');
  lines.push('export function getOrbitSubagentAvatarAssetById(id: string | null | undefined): OrbitSubagentAvatarAsset | null {');
  lines.push('  if (id === null || id === undefined || id.length === 0) {');
  lines.push('    return null;');
  lines.push('  }');
  lines.push('  const found = AVATAR_ASSET_BY_ID.get(id);');
  lines.push('  return found !== undefined ? found : null;');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const args = process.argv.slice(2);
  const checkMode = args.includes('--check');
  const unknownArgs = args.filter((a) => a !== '--check');
  if (unknownArgs.length > 0) {
    fail(`Unknown arguments: ${unknownArgs.join(' ')}. Usage: node scripts/gen-harmony-avatars.mjs [--check]`);
  }

  const mod = await import(pathToFileURL(DESKTOP_AVATAR_TS).href);
  const roster = mod.SUBAGENT_AVATAR_ROSTER;
  if (!Array.isArray(roster) || roster.length === 0) {
    fail(`SUBAGENT_AVATAR_ROSTER missing or empty in ${DESKTOP_AVATAR_TS}`);
  }

  const expectedSvgs = new Map();
  const lightColorEntries = [];
  const darkColorEntries = [];

  for (const ch of roster) {
    const slug = toResourceSlug(ch.id);
    const svgName = `orbit_avatar_${slug}.svg`;
    expectedSvgs.set(svgName, buildAvatarSvg(ch));
    lightColorEntries.push({ name: `orbit_avatar_${slug}_bg`, value: ch.lightBg });
    darkColorEntries.push({ name: `orbit_avatar_${slug}_bg`, value: ch.darkBg });
  }

  const expectedBaseColor = mergeColorJson(BASE_COLOR_PATH, lightColorEntries);
  const expectedDarkColor = mergeColorJson(DARK_COLOR_PATH, darkColorEntries);
  const expectedRosterEts = buildRosterEts(roster);

  if (checkMode) {
    const diffs = [];
    const existingSvgNames = existsSync(MEDIA_DIR)
      ? readdirSync(MEDIA_DIR).filter((name) => AVATAR_SVG_RE.test(name)).sort()
      : [];
    for (const existingName of existingSvgNames) {
      if (!expectedSvgs.has(existingName)) {
        diffs.push(`Unexpected stale avatar SVG: ${join(MEDIA_DIR, existingName)}`);
      }
    }
    for (const [svgName, expected] of expectedSvgs.entries()) {
      const svgPath = join(MEDIA_DIR, svgName);
      if (!existsSync(svgPath)) {
        diffs.push(`Missing avatar SVG: ${svgPath}`);
      } else if (readFileSync(svgPath, 'utf8') !== expected) {
        diffs.push(`Out of sync avatar SVG: ${svgPath}`);
      }
    }
    if (!existsSync(BASE_COLOR_PATH) || readFileSync(BASE_COLOR_PATH, 'utf8') !== expectedBaseColor) {
      diffs.push(`Out of sync color resource: ${BASE_COLOR_PATH}`);
    }
    if (!existsSync(DARK_COLOR_PATH) || readFileSync(DARK_COLOR_PATH, 'utf8') !== expectedDarkColor) {
      diffs.push(`Out of sync color resource: ${DARK_COLOR_PATH}`);
    }
    if (!existsSync(ROSTER_ETS_PATH) || readFileSync(ROSTER_ETS_PATH, 'utf8') !== expectedRosterEts) {
      diffs.push(`Out of sync roster file: ${ROSTER_ETS_PATH}`);
    }
    if (diffs.length > 0) {
      for (const d of diffs) {
        console.error(d);
      }
      console.error('Run `node scripts/gen-harmony-avatars.mjs` to regenerate HarmonyOS avatar assets.');
      process.exit(1);
    }
    console.log(`Verified ${roster.length} HarmonyOS subagent avatar SVGs, colors, and OrbitAvatarRoster.ets.`);
    return;
  }

  mkdirSync(MEDIA_DIR, { recursive: true });
  for (const existingName of readdirSync(MEDIA_DIR).filter((name) => AVATAR_SVG_RE.test(name))) {
    if (!expectedSvgs.has(existingName)) {
      unlinkSync(join(MEDIA_DIR, existingName));
    }
  }
  for (const [svgName, content] of expectedSvgs.entries()) {
    writeFileSync(join(MEDIA_DIR, svgName), content, 'utf8');
  }
  writeFileSync(BASE_COLOR_PATH, expectedBaseColor, 'utf8');
  writeFileSync(DARK_COLOR_PATH, expectedDarkColor, 'utf8');
  mkdirSync(dirname(ROSTER_ETS_PATH), { recursive: true });
  writeFileSync(ROSTER_ETS_PATH, expectedRosterEts, 'utf8');

  console.log(`Generated ${roster.length} HarmonyOS subagent avatar SVGs, colors, and OrbitAvatarRoster.ets.`);
}

main().catch((err) => {
  fail(err instanceof Error ? err.stack || err.message : String(err));
});
